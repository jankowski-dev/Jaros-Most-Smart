function shuffle(array, rng) {
    const result = [...array];
    for (let i = result.length - 1; i > 0; i--) {
        const j = Math.floor(rng() * (i + 1));
        [result[i], result[j]] = [result[j], result[i]];
    }
    return result;
}

function additionPool(limit) {
    const pool = [];
    for (let a = 0; a <= limit; a++) {
        for (let b = 0; b <= limit - a; b++) {
            pool.push({ num1: a, num2: b, operator: '+', answer: a + b });
        }
    }
    return pool;
}

function subtractionPool(limit) {
    const pool = [];
    for (let a = 0; a <= limit; a++) {
        for (let b = 0; b <= a; b++) {
            pool.push({ num1: a, num2: b, operator: '-', answer: a - b });
        }
    }
    return pool;
}

const easyMathPool = additionPool(10);
const hardMathPool = [...additionPool(20), ...subtractionPool(20)];

export function generateMathProblems(level, count = 10, rng = Math.random) {
    const pool = level === 'hard' ? hardMathPool : easyMathPool;
    const take = Math.max(0, Math.min(Math.floor(count), pool.length));
    return shuffle(pool, rng).slice(0, take).map(problem => ({ ...problem }));
}
